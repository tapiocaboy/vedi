export type TranslationKey = keyof typeof en;

export const translations: Record<Lang, Record<TranslationKey, string>> = { en, si };

/** Interpolate {key} placeholders in a translation string. */
export function interpolate(
  template: string,
  vars: Record<string, string | number>,
): string {
  return template.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

export function translate(key: TranslationKey, lang?: Lang): string {
  const l = lang ?? (typeof localStorage !== 'undefined' && localStorage.getItem('trytellme_lang') === 'si' ? 'si' : 'en');
  return translations[l][key] ?? translations.en[key];
}
